//! Room layouts and their story text.
//!
//! Legend: `#` rock, `~` water, `=` cracked wall, `C` crystal, `^` spikes,
//! `o` magic ore, `g` hipokute grass, `D` sealed door, `X` exit, `P` spawn,
//! `1`-`9` story triggers, `b` bat, `s` spider, `c` centipede, `a` armor saurus,
//! `S` tempest serpent, `V` Veldora, `k` adventurer. Short rows are padded with rock.

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Who {
    Sage,
    Rimuru,
    Veldora,
    Kabal,
    Eren,
    Gido,
}

impl Who {
    pub fn name(self) -> &'static str {
        match self {
            Who::Sage => "Great Sage",
            Who::Rimuru => "Rimuru",
            Who::Veldora => "Veldora",
            Who::Kabal => "Kabal",
            Who::Eren => "Eren",
            Who::Gido => "Gido",
        }
    }
}

pub struct RoomDef {
    pub name: &'static str,
    pub map: &'static str,
    /// Dark until the slime has Magic Sense.
    pub dark: bool,
    pub on_enter: &'static [(Who, &'static str)],
    pub triggers: &'static [(u8, Who, &'static str)],
}

